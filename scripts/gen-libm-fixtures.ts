for (const x of log1pXs) add1("log1p", x, decOf(1).plus(decOf(x)).ln());

const trigXs = [0, 1e-8, -1e-8, 0.1, -0.1, 0.5, 1, -1, Math.PI / 6, Math.PI / 2, Math.PI, -Math.PI / 2, 2, -2, 10, 100, 1000, 1e5, 2 ** 19, 2 ** 20 - 1024, -(2 ** 19), 0.3, 4, -8, 2 ** 20 * 0.5];
for (const x of trigXs) {
  const d = decOf(x);
  add1("sin", x, d.sin());
  add1("cos", x, d.cos());
}

