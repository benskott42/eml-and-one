/**
 * Offline correctly rounded references for the libm self-test.
 * decimal.js at 100 digits, then round-to-nearest-even via Number().
 * Run: npx tsx scripts/gen-libm-fixtures.ts
 */
import { writeFileSync } from "node:fs";
import { Decimal } from "decimal.js";
import path from "node:path";
import { fileURLToPath } from "node:url";

const D = Decimal.clone({ precision: 100 });

function decOf(n: number): InstanceType<typeof D> {
  if (!Number.isFinite(n)) return new D(n);
  const buf = new ArrayBuffer(8);
  const view = new DataView(buf);
  view.setFloat64(0, n, false);
  const hi = view.getUint32(0, false);
  const lo = view.getUint32(4, false);
  const sign = hi >>> 31 ? -1 : 1;
  const exp = (hi >>> 20) & 0x7ff;
  const frac = new D(hi & 0xfffff).mul(new D(2).pow(32)).add(lo);
  if (exp === 0) {
    if (frac.isZero()) return sign < 0 ? new D(0).neg() : new D(0);
    const mag = frac.mul(new D(2).pow(-1074));
    return sign < 0 ? mag.neg() : mag;
  }
  const mant = frac.add(new D(2).pow(52));
  const mag = mant.mul(new D(2).pow(exp - 1075));
  return sign < 0 ? mag.neg() : mag;
}

/** Correctly rounded float64 of a high-precision value. V8's Number() is round-ties-to-even. */
function toFloat64(x: InstanceType<typeof D>): number {
  if (!x.isFinite()) return x.isNaN() ? Number.NaN : x.isNeg() ? Number.NEGATIVE_INFINITY : Number.POSITIVE_INFINITY;
  if (x.isZero()) return x.isNeg() ? -0 : 0;
  const text = (x.isNeg() ? "-" : "") + x.abs().toExponential(40);
  return Number(text);
}

function toHex(n: number): string {
  const buf = new ArrayBuffer(8);
  const view = new DataView(buf);
  view.setFloat64(0, n, true);
  const lo = view.getUint32(0, true).toString(16).padStart(8, "0");
  const hi = view.getUint32(4, true).toString(16).padStart(8, "0");
  return lo + hi;
}

type Entry = { fn: string; x: string; y?: string; expect: string };

const entries: Entry[] = [];

function add1(fn: string, x: number, value: InstanceType<typeof D>) {
  const expect = toFloat64(value);
  if (!Number.isFinite(expect) || !Number.isFinite(x)) return;
  entries.push({ fn, x: toHex(x), expect: toHex(expect) });
}

function add2(fn: string, x: number, y: number, value: InstanceType<typeof D>) {
  const expect = toFloat64(value);
  if (!Number.isFinite(expect) || !Number.isFinite(x) || !Number.isFinite(y)) return;
  entries.push({ fn, x: toHex(x), y: toHex(y), expect: toHex(expect) });
}

const expXs = [0, 1, -1, 0.5, -0.5, 2, -2, 10, -10, 20, -20, 40, -40, 100, -100, 300, -300, 699, -699, 699.5, -699.5, Math.LN2, Math.PI, 0.1, -0.1, 1e-8, -1e-8, 1e-4, -3, 7, -15, 0.25, -0.25, 6];
for (const x of expXs) add1("exp", x, decOf(x).exp());

const expm1Xs = [0, 1e-16, -1e-16, 1e-12, -1e-12, 1e-8, -1e-8, 1e-4, -1e-4, 0.1, -0.1, 1, -0.5, 2, -0.9, 10, -5, 20, 1e-6, -0.999, 3, -2];
for (const x of expm1Xs) add1("expm1", x, decOf(x).exp().sub(1));

const logXs = [1, 2, 0.5, 10, 0.1, Math.E, 1e-8, 1e8, 1e20, 1e100, 1e-100, 1 + 1e-8, 0.9, 4, Math.PI, 3, 100, 1.0000001, 2 ** -10, 2 ** 10, 7, 0.25, 50, 1e-3];
for (const x of logXs) add1("log", x, decOf(x).ln());

