import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { LEAN_VERIFIED_THEOREMS, nodeToLean4Snippet } from "../lib/eml/export";
import { certifyRpnForLean, rpnToLeanBits } from "../lib/eml/leanCert";
import { E, ONE, V, nodeFromRpn } from "../lib/eml/node";
import { isProgram } from "../lib/eml/programIndex";

/**
 * End-to-end bridge verifier between TypeScript (`lib/eml/`) and Lean 4 (`formal/lean/`):
 *
 * 1. Verifies every entry in `LEAN_VERIFIED_THEOREMS`:
 *    - `formal/lean/Eml/<file>` exists
 *    - `@<theorem>` exists in `Eml` AND its exact `List Bool` argument equals `rpn`
 *    - `model` ("C" vs "EmlExt") matches the theorem's actual evaluator (`eml` vs `extEml`)
 *    - its stored `lean` value term is exactly the value the theorem proves
 * 2. Compiles sample outputs of `nodeToLean4Snippet` (certified theorem, record, and
 *    symbolic variable circuit) directly with Lean 4.
 * 3. Cross-checks `certifyRpnForLean` against `Eml.Cert.certify` on every valid
 *    EML program up to K = 9 (23 programs) plus sample records.
 */

const repoRoot = path.resolve(__dirname, "..");
const leanDir = path.join(repoRoot, "formal", "lean");
const outPath = path.join(leanDir, ".lake", "UiCrossCheck.lean");

function enumerateValidPrograms(maxGates: number): string[] {
  const byGates: string[][] = [["1"]];
  for (let g = 1; g <= maxGates; g += 1) {
    const cur: string[] = [];
    for (let left = 0; left < g; left += 1) {
      const right = g - 1 - left;
      for (const a of byGates[left]!) {
        for (const b of byGates[right]!) {
          cur.push(`${a}${b}E`);
        }
      }
    }
    byGates.push(cur);
  }
  return byGates.flat();
}

const lines: string[] = [
  "/- Auto-generated by scripts/lean-bridge-check.ts. Do not edit by hand. -/",
  "import Eml",
  "",
  "open Eml Eml.Binary Eml.Extended Eml.Cert",
  "",
  "namespace UiCrossCheck",
  "",
];

// 1. Cross-check every entry in LEAN_VERIFIED_THEOREMS
let idx = 0;
for (const [rpn, ref] of Object.entries(LEAN_VERIFIED_THEOREMS)) {
  if (!isProgram(rpn)) {
    throw new Error(`Invalid RPN in LEAN_VERIFIED_THEOREMS: ${rpn}`);
  }
  const leanFile = path.join(leanDir, "Eml", ref.file);
  if (!fs.existsSync(leanFile)) {
    throw new Error(`Missing Lean file referenced by LEAN_VERIFIED_THEOREMS: ${leanFile}`);
  }
  const bits = rpnToLeanBits(rpn);
  const lhs =
    ref.model === "C"
      ? `evalRpn (1 : ℂ) eml ${bits} []`
      : `evalRpn (EmlExt.finite 1) extEml ${bits} []`;
  // The stored value term is exactly what the theorem proves, not just "some value".
  lines.push(`example : ${lhs} = some [${ref.lean}] := ${ref.theorem}`);
  idx += 1;
}

lines.push("");

// 2. Cross-check certifyRpnForLean against Eml.Cert.certify on all valid programs up to K = 9
const samplePrograms = [
  ...enumerateValidPrograms(4), // K = 1, 3, 5, 7, 9 (23 programs)
  "111E1EE11EE",
  "11111EEE1EE11E1EE",
  "111111EEE1EE11EE1EE",
];

let certMatches = 0;
for (const rpn of samplePrograms) {
  const bits = rpnToLeanBits(rpn);
  const cert = certifyRpnForLean(rpn);
  const rhs = cert ? `some (${cert.leanSym})` : "none";
  lines.push(`example : certify ${bits} = ${rhs} := by decide`);
  certMatches += 1;
}

lines.push("");
lines.push("end UiCrossCheck");
lines.push("");

// 3. Compile sample snippets from nodeToLean4Snippet in isolated namespaces
const snippetCases: Array<{ name: string; node: ReturnType<typeof nodeFromRpn> }> = [
  { name: "SnippetZero", node: nodeFromRpn("111E1EE".split("")) },
  { name: "SnippetE", node: E(ONE, ONE) },
  { name: "SnippetTwo", node: nodeFromRpn("111111EEE1EE11EE1EE".split("")) },
  { name: "SnippetPi", node: nodeFromRpn("1111111111E1EEEE11E1E1EEEE1EEE1EE111111111EEE1EE11EE1EEEE1EE1111111E1EEEE11E1E1EEEE1EE1E1EE1E".split("")) },
  { name: "SnippetVar", node: E(V("x"), ONE) },
];

for (const sc of snippetCases) {
  const snippet = nodeToLean4Snippet(sc.node);
  if (!snippet) {
    throw new Error(`nodeToLean4Snippet returned null for ${sc.name}`);
  }
  // Strip leading `import ...` lines since `import Eml` is already at top of file.
  const body = snippet
    .split(/\r?\n/)
    .filter((l) => !l.startsWith("import "))
    .join("\n");
  lines.push(`namespace ${sc.name}`);
  lines.push(body);
  lines.push(`end ${sc.name}`);
  lines.push("");
}

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join("\n"), "utf8");

if (process.argv.includes("--generate-only")) {
  console.log(
    `Generated ${outPath} (${idx} record checks, ${certMatches} cert checks, ${snippetCases.length} snippet checks).`,
  );
  process.exit(0);
}

const elanBin = path.join(process.env.USERPROFILE || process.env.HOME || "", ".elan", "bin");
const env = { ...process.env };
if (fs.existsSync(elanBin)) {
  env.PATH = `${elanBin}${path.delimiter}${env.PATH || ""}`;
}

execFileSync("lake", ["env", "lean", outPath], {
  cwd: leanDir,
  env,
  stdio: "inherit",
});

console.log(
  `Lean bridge check passed: ${idx} UI theorem links, ${certMatches} Cert.certify cross-checks, ${snippetCases.length} compiled snippets.`,
);
